const MATH_LETTER_BLOCKS = [
  [0x1d400, true], [0x1d41a, false],
  [0x1d434, true], [0x1d44e, false],
  [0x1d468, true], [0x1d482, false],
  [0x1d49c, true], [0x1d4b6, false],
  [0x1d4d0, true], [0x1d4ea, false],
  [0x1d504, true], [0x1d51e, false],
  [0x1d538, true], [0x1d552, false],
  [0x1d56c, true], [0x1d586, false],
  [0x1d5a0, true], [0x1d5ba, false],
  [0x1d5d4, true], [0x1d5ee, false],
  [0x1d608, true], [0x1d622, false],
  [0x1d63c, true], [0x1d656, false],
  [0x1d670, true], [0x1d68a, false],
];

function mathLetterToAscii(code) {
  const mapped = FONT_MAP[String.fromCodePoint(code)];
  if (mapped) return mapped;
  for (const [start, upper] of MATH_LETTER_BLOCKS) {
    if (code >= start && code < start + 26) {
      return String.fromCharCode((upper ? 65 : 97) + (code - start));
    }
  }
  return null;
}

function normalizeText(input) {
  if (input == null) return "";
  let out = "";
  const str = String(input).normalize("NFKD");
  for (const ch of str) {
    if (FONT_MAP[ch]) {
      out += FONT_MAP[ch];
      continue;
    }
    const code = ch.codePointAt(0);
    const mapped = mathLetterToAscii(code);
    if (mapped) {
      out += mapped.toLowerCase();
      continue;
    }
    if (code >= 0xff21 && code <= 0xff3a) {
      out += String.fromCharCode(65 + (code - 0xff21)).toLowerCase();
      continue;
    }
    if (code >= 0xff41 && code <= 0xff5a) {
      out += String.fromCharCode(97 + (code - 0xff41));
      continue;
    }
    out += ch;
  }
  return out.toLowerCase().replace(/[\u0300-\u036f]/g, "").trim();
}

function toSmallCaps(input) {
  return String(input || "")
    .split("")
    .map((ch) => SMALL_CAPS_MAP[ch.toLowerCase()] || ch)
    .join("");
}

const JARVIS_TRIGGERS = ["jarvis", "hey jarvis", "hi jarvis", "hello jarvis", "@jarvis"];

function isJarvisMention(text) {
  const n = normalizeText(text);
  if (!n) return false;
  if (JARVIS_TRIGGERS.some((t) => n === t || n.startsWith(t + " ") || n.startsWith(t + ","))) {
    return true;
  }
  if (/\bjarvis\b/.test(n) || n.includes("@jarvis")) return true;
  return false;
}

function stripJarvis(text) {
  return String(text || "")
    .replace(/^[@]?\s*(hey|hi|hello)?\s*jarvis[,!\s:-]*/i, "")
    .replace(/^[@]?\s*(ʜᴇʏ|ʜɪ|ʜᴇʟʟᴏ)?\s*ᴊᴀʀᴠɪs[,!\s:-]*/i, "")
    .trim();
}

function fontCount() {
  return Object.keys(FONT_MAP).length;
}

